// Writes src/lib/iconPaths.ts, the app's icons (#338): each one's SVG path,
// from Material Symbols Outlined, the icon font the app drew them with
// before, at the font's 24 px optical size.
//
//   npm run icons:gen                          fetch every icon the file lists again
//   npm run icons:gen -- <name>[:fill|:pin]…   add icons to it, leaving the rest as they are
//
// `<name>` is the outlined icon <Icon name="…"> draws, by its name on
// fonts.google.com/icons. `<name>:fill` adds that and its filled cut, which
// <Icon fill> draws; `<name>:pin` adds the cut a map pin's glyph draws
// (filled, weight 500; src/lib/mapPins.ts). To drop an icon nothing draws
// any more, delete its entry and run this again.
//
// The SVGs are the ones fonts.google.com/icons downloads (SVG_BASE), drawn
// from the font Google Fonts serves: every icon the app had matched it to
// the pixel. Google's material-design-icons repository lags it (its explore
// and ios_share are older drawings, and it has no terrain), so it isn't
// used. The release isn't versioned, so adding an icon fetches only that
// one, and a bare run, which fetches them all, brings in any Google has
// redrawn since, as the font did by itself: check the visual diffs (and
// src/lib/iconMetrics.ts's measurements) after one. Only this script uses
// the network; the app ships the paths.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { ScriptError, runAsScript } from './run-as-script.ts';

const SVG_BASE = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined';
const OUT = 'src/lib/iconPaths.ts';

/** An icon's cuts: outlined, filled, and a map pin's. */
export type Cut = 'outline' | 'fill' | 'pin';
const CUTS: readonly Cut[] = ['outline', 'fill', 'pin'];
// Each cut's style in Google's downloads, and its list in the generated file.
const STYLE: Record<Cut, string> = { outline: 'default', fill: 'fill1', pin: 'wght500fill1' };
const LIST: Record<Cut, string> = { outline: 'ICONS', fill: 'FILLED_ICONS', pin: 'PIN_ICONS' };

/** Each cut's paths, by icon name. */
export type Paths = Record<Cut, Map<string, string>>;

/** Where Google keeps one cut of an icon, as an SVG. */
export function svgUrl(name: string, cut: Cut): string {
  return `${SVG_BASE}/${name}/${STYLE[cut]}/24px.svg`;
}

/**
 * The path an icon's SVG draws, or null if it isn't an icon as Google draws
 * them: one path, in the 960-unit box (viewBox 0 -960 960 960) every icon
 * the app draws shares, <Icon>'s and the pins' alike. Its data is held to
 * commands, figures, spaces and commas, as Google writes it, since it goes
 * into a quoted string in the generated file and into the pins' HTML.
 */
export function pathOf(svg: string): string | null {
  const open = /<svg\b[^>]*>/.exec(svg)?.[0];
  if (!open || !/\sviewBox="0 -960 960 960"/.test(open)) return null;
  if ((svg.match(/<path\b/g) ?? []).length !== 1) return null;
  const d = /<path\b[^>]*?\sd="([^"]*)"/.exec(svg)?.[1];
  return d && /^[MmLlHhVvCcSsQqTtAaZz0-9., -]+$/.test(d) ? d : null;
}

/** A command-line icon (`name`, `name:fill`, `name:pin`) as its cuts, or null if it isn't one. */
export function parseIcon(arg: string): { name: string; cuts: Cut[] } | null {
  const match = /^([a-z0-9_]+)(?::(fill|pin))?$/.exec(arg);
  if (!match) return null;
  const [, name, variant] = match;
  if (variant === 'pin') return { name, cuts: ['pin'] };
  // A filled icon is drawn outlined too, when it isn't filled.
  return { name, cuts: variant === 'fill' ? ['outline', 'fill'] : ['outline'] };
}

/** The paths a generated file lists, of each cut. */
export function pathsIn(text: string): Paths {
  const paths: Paths = { outline: new Map(), fill: new Map(), pin: new Map() };
  for (const cut of CUTS) {
    const list = new RegExp(`export const ${LIST[cut]} = \\{([^}]*)\\}`).exec(text)?.[1] ?? '';
    for (const [, name, d] of list.matchAll(/^\s+'?([a-z0-9_]+)'?:\s*'([^']*)'/gm)) {
      paths[cut].set(name, d);
    }
  }
  return paths;
}

/** The generated file's text, before Prettier lays it out, for these paths. */
export function renderIcons(paths: Paths): string {
  const list = (cut: Cut) =>
    [...paths[cut]]
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([name, d]) => `  '${name}': '${d}',`)
      .join('\n');
  return `// Generated by scripts/gen-icons.ts from Material Symbols Outlined (Google,
// Apache-2.0): don't edit a path by hand. \`npm run icons:gen -- <name>\` adds
// an icon, and the script's header says the rest. Each is one SVG path in
// Google's 960-unit box (viewBox 0 -960 960 960), at the 24 px optical size.

/** The outlined icons, which <Icon name="…"> draws. */
export const ICONS = {
${list('outline')}
} as const;

/** Their filled cut, which <Icon fill> draws. */
export const FILLED_ICONS = {
${list('fill')}
} as const;

/** A map pin's glyphs: filled, at weight 500 (src/lib/mapPins.ts). */
export const PIN_ICONS = {
${list('pin')}
} as const;

export type IconName = keyof typeof ICONS;
export type FillableIconName = keyof typeof FILLED_ICONS;
export type PinIconName = keyof typeof PIN_ICONS;
`;
}

/** What main reads, fetches and writes through, so a test can stand in for each. */
export interface Io {
  fetch: (url: string) => Promise<{ ok: boolean; status: number; text: () => Promise<string> }>;
  read: (file: string) => string | null;
  write: (file: string, text: string) => void;
}

const nodeIo: Io = {
  fetch: (url) => fetch(url),
  read: (file) => (existsSync(file) ? readFileSync(file, 'utf8') : null),
  write: (file, text) => writeFileSync(file, text),
};

/**
 * Adds the icons `argv` names to the file, fetching only those, or with none
 * named fetches every icon it lists again; writes the file, laid out by
 * Prettier. Writes nothing if an icon can't be had.
 */
export async function main(argv: readonly string[], io: Io = nodeIo, out = OUT): Promise<void> {
  const paths = pathsIn(io.read(out) ?? '');
  const wanted: { name: string; cut: Cut }[] = [];
  for (const arg of argv) {
    const icon = parseIcon(arg);
    if (!icon) {
      throw new ScriptError(`gen-icons: "${arg}" isn't <name>, <name>:fill or <name>:pin`, 2);
    }
    for (const cut of icon.cuts) {
      if (!paths[cut].has(icon.name)) wanted.push({ name: icon.name, cut });
    }
  }
  if (!argv.length) {
    wanted.push(...CUTS.flatMap((cut) => [...paths[cut].keys()].map((name) => ({ name, cut }))));
    if (!wanted.length) throw new ScriptError(`gen-icons: ${out} lists no icons; name one`, 2);
  }
  const fetched = await Promise.all(
    wanted.map(async ({ name, cut }) => {
      const url = svgUrl(name, cut);
      let why: string;
      try {
        const response = await io.fetch(url);
        const d = response.ok ? pathOf(await response.text()) : null;
        if (d !== null) return { name, cut, d };
        why = response.ok ? "isn't a one-path icon" : `HTTP ${response.status}`;
      } catch (error) {
        why = error instanceof Error ? error.message : String(error);
      }
      throw new ScriptError(`gen-icons: no ${cut} cut of "${name}" (${url}: ${why})`, 1);
    }),
  );
  for (const { name, cut, d } of fetched) paths[cut].set(name, d);
  const text = await format(renderIcons(paths), { ...(await resolveConfig(out)), filepath: out });
  io.write(out, text);
  const icons = new Set(CUTS.flatMap((cut) => [...paths[cut].keys()])).size;
  const cuts = CUTS.map((cut) => `${paths[cut].size} ${cut}`).join(', ');
  console.log(`fetched ${fetched.length}; ${out} has ${icons} icons (${cuts})`);
}

runAsScript(import.meta.url, main);
