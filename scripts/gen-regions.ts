// Writes shared/isoRegions.ts, the regions beyond California (#274), from
// ISO 3166 as Debian's iso-codes package publishes it: every country's
// first-level subdivisions (US-OR, JP-26, CA-BC), and each country that has
// none (HK) as a whole. California itself is left out: the app's own areas
// (shared/regions.ts) divide it.
//
//   node --experimental-strip-types scripts/gen-regions.ts [iso-codes json dir]
//
// The directory defaults to /usr/share/iso-codes/json (apt install iso-codes).

import { readFileSync, writeFileSync } from 'node:fs';

interface Country {
  alpha_2: string;
  name: string;
  common_name?: string;
}
interface Subdivision {
  code: string;
  name: string;
  parent?: string;
}

const dir = process.argv[2] ?? '/usr/share/iso-codes/json';
const read = <T>(file: string, key: string) =>
  (JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')) as Record<string, T[]>)[key];
const countries = read<Country>('iso_3166-1.json', '3166-1');
const subdivisions = read<Subdivision>('iso_3166-2.json', '3166-2').filter(
  (s) => !s.parent && s.code !== 'US-CA',
);
const countryName = new Map(countries.map((c) => [c.alpha_2, c.common_name ?? c.name]));
const divided = new Set(subdivisions.map((s) => s.code.split('-')[0]));
const rows: [string, string, string][] = [
  ...subdivisions.map((s): [string, string, string] => [
    s.code,
    s.name,
    countryName.get(s.code.split('-')[0]) ?? '',
  ]),
  ...countries
    .filter((c) => !divided.has(c.alpha_2))
    .map((c): [string, string, string] => [c.alpha_2, c.common_name ?? c.name, '']),
];
// By country, then by name, so a country's own list reads in order.
const sortKey = (r: [string, string, string]) => `${r[2] || r[1]}\u0000${r[1]}`;
rows.sort((a, b) => sortKey(a).localeCompare(sortKey(b), 'en'));

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
writeFileSync(
  'shared/isoRegions.ts',
  `// Generated by scripts/gen-regions.ts from ISO 3166 (Debian iso-codes): don't
// edit by hand. Each region beyond California (#274): its ISO code, its name,
// and its country's name ('' for a country that is a region itself).
export const ISO_REGIONS = [
${rows.map((r) => `  [${r.map(q).join(', ')}],`).join('\n')}
] as const;
`,
);
console.log(`${rows.length} regions`);
