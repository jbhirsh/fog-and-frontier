// Writes shared/isoRegions.ts, the regions beyond California (#274), from
// ISO 3166 as Debian's iso-codes package publishes it: every country's
// first-level subdivisions (US-OR, JP-26, CA-BC), and each country that has
// none (HK) as a whole. California itself is left out: the app's own areas
// (shared/regions.ts) divide it.
//
//   node --experimental-strip-types scripts/gen-regions.ts [iso-codes json dir]
//
// The directory defaults to /usr/share/iso-codes/json (apt install iso-codes).

import { readFileSync, writeFileSync } from 'node:fs';
import { ScriptError, runAsScript } from './run-as-script.ts';

interface Country {
  alpha_2: string;
  name: string;
  common_name?: string;
}
interface Subdivision {
  code: string;
  name: string;
  parent?: string;
}
/** A region's ISO code, its name, and its country's name ('' for a country). */
type Row = [string, string, string];

const DEFAULT_DIR = '/usr/share/iso-codes/json';
const OUT = 'shared/isoRegions.ts';

/**
 * Every first-level subdivision but California, then each country with none,
 * by country and then by name, so a country's own list reads in order.
 */
export function regionRows(
  countries: readonly Country[],
  subdivisions: readonly Subdivision[],
): Row[] {
  const firstLevel = subdivisions.filter((s) => !s.parent && s.code !== 'US-CA');
  const countryName = new Map(countries.map((c) => [c.alpha_2, c.common_name ?? c.name]));
  const divided = new Set(firstLevel.map((s) => s.code.split('-')[0]));
  const rows: Row[] = [
    ...firstLevel.map((s): Row => [s.code, s.name, countryName.get(s.code.split('-')[0]) ?? '']),
    ...countries
      .filter((c) => !divided.has(c.alpha_2))
      .map((c): Row => [c.alpha_2, c.common_name ?? c.name, '']),
  ];
  const sortKey = (r: Row) => `${r[2] || r[1]}\u0000${r[1]}`;
  return rows.sort((a, b) => sortKey(a).localeCompare(sortKey(b), 'en'));
}

// The characters a single-quoted literal can't hold as they are: the quote,
// the backslash, and the line terminators.
const ESCAPES: Record<string, string> = {
  "'": "\\'",
  '\\': '\\\\',
  '\n': '\\n',
  '\r': '\\r',
  '\u2028': '\\u2028',
  '\u2029': '\\u2029',
};

/** A single-quoted TypeScript string literal holding `s` exactly. */
export function quote(s: string): string {
  return `'${s.replace(/['\\\n\r\u2028\u2029]/g, (c) => ESCAPES[c] ?? c)}'`;
}

/** shared/isoRegions.ts's text for these rows. */
export function renderRegions(rows: readonly Row[]): string {
  return `// Generated by scripts/gen-regions.ts from ISO 3166 (Debian iso-codes): don't
// edit by hand. Each region beyond California (#274): its ISO code, its name,
// and its country's name ('' for a country that is a region itself).
export const ISO_REGIONS = [
${rows.map((r) => `  [${r.map(quote).join(', ')}],`).join('\n')}
] as const;
`;
}

/** Reads iso-codes from argv[0] (or DEFAULT_DIR) and writes the regions file. */
export function main(argv: readonly string[], out = OUT): Promise<void> {
  const dir = argv[0] ?? DEFAULT_DIR;
  // A file without its list is refused: writing no regions would empty the
  // app's region list.
  const read = <T>(file: string, key: string): T[] => {
    const list = (JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')) as Record<string, T[]>)[key];
    if (!Array.isArray(list)) {
      throw new ScriptError(`gen-regions: ${dir}/${file} has no "${key}" list`, 1);
    }
    return list;
  };
  // In a promise, so a refusal rejects the one runAsScript waits on.
  return Promise.resolve().then(() => {
    const rows = regionRows(
      read<Country>('iso_3166-1.json', '3166-1'),
      read<Subdivision>('iso_3166-2.json', '3166-2'),
    );
    writeFileSync(out, renderRegions(rows));
    console.log(`${rows.length} regions`);
  });
}

runAsScript(import.meta.url, main);
